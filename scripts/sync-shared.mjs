// Copies the web project's shared TypeScript (src/shared) into src/shared/.
// Mobile never edits these files: change them in the web project and re-run
// `npm run sync:shared` (MobileApp_Architecture.md §3.1, webapp doc §4).
//
//   WEBAPP_DIR=../path/to/web-app npm run sync:shared
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webapp = resolve(process.env.WEBAPP_DIR ?? join(root, '..', 'college-attendance-system'));
const from = join(webapp, 'src', 'shared');
const to = join(root, 'src', 'shared');

// Web-only modules (the blueprint is edited on the web, never on mobile).
const SKIP = new Set(['blueprint']);

if (!existsSync(from)) {
  console.error(`No shared folder at ${from}. Set WEBAPP_DIR to the web project.`);
  process.exit(1);
}

rmSync(to, { recursive: true, force: true });
let count = 0;
function copy(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const src = join(dir, entry.name);
    if (entry.isDirectory()) {
      copy(src);
      continue;
    }
    if (!/\.tsx?$/.test(entry.name)) continue;
    const dest = join(to, relative(from, src));
    mkdirSync(dirname(dest), { recursive: true });
    const header = `// GENERATED by scripts/sync-shared.mjs from Webapp/src/shared/${relative(from, src).replace(/\\/g, '/')}. Edit it in the web project.\n`;
    writeFileSync(dest, header + readFileSync(src, 'utf8'));
    count++;
  }
}
copy(from);
console.log(`Synced ${count} shared files into src/shared`);
